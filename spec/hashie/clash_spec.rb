# frozen_string_literal: true

require 'spec_helper'

module SerializationFixtures
  class Clash < Hashie::Clash; end
end

describe Hashie::Clash do
  it 'is able to set an attribute via method_missing' do
    subject.foo('bar')
    expect(subject[:foo]).to eq 'bar'
  end

  it 'is able to set multiple attributes' do
    subject.foo('bar').baz('wok')
    expect(subject).to eq(foo: 'bar', baz: 'wok')
  end

  it 'converts multiple arguments into an array' do
    subject.foo(1, 2, 3)
    expect(subject[:foo]).to eq [1, 2, 3]
  end

  it 'is able to use bang notation to create a new Clash on a key' do
    subject.foo!
    expect(subject[:foo]).to be_a(described_class)
  end

  it 'is able to chain onto the new Clash when using bang notation' do
    subject.foo!.bar('abc').baz(123)
    expect(subject).to eq(foo: { bar: 'abc', baz: 123 })
  end

  it 'is able to jump back up to the parent in the chain with #_end!' do
    subject.foo!.bar('abc')._end!.baz(123)
    expect(subject).to eq(foo: { bar: 'abc' }, baz: 123)
  end

  it 'merges rather than replaces existing keys' do
    subject.where(abc: 'def').where(hgi: 123)
    expect(subject).to eq(where: { abc: 'def', hgi: 123 })
  end

  it 'is able to replace all of its own keys with #replace' do
    subject.foo(:bar).hello(:world)
    expect(subject.replace(baz: 123, hgi: 123)).to eq(baz: 123, hgi: 123)
    expect(subject).to eq(baz: 123, hgi: 123)
    expect(subject[:foo]).to be_nil
    expect(subject[:hello]).to be_nil
  end

  it 'merges multiple bang notation calls' do
    subject.where!.foo(123)
    subject.where!.bar(321)
    expect(subject).to eq(where: { foo: 123, bar: 321 })
  end

  it 'raises an exception when method is missing' do
    expect { subject.boo }.to raise_error(NoMethodError)
  end

  it 'is able to set the id key via method_missing' do
    subject.id('123')
    expect(subject[:id]).to eq '123'
  end

  it 'is able to chain into an existing plain hash value' do
    subject[:foo] = Hashie::Hash[bar: 'abc']
    subject.foo!.baz(123)
    expect(subject).to eq(foo: { bar: 'abc', baz: 123 })
    expect(subject[:foo]).to be_a(described_class)
  end

  it 'raises a ChainError when chaining into a non-hash key' do
    subject.foo('bar')
    expect do
      subject.foo!
    end.to raise_error(Hashie::Clash::ChainError, 'tried to chain into a non-hash key')
  end

  describe '#respond_to?' do
    it 'is true for bang methods when the key is unset' do
      expect(subject.respond_to?(:foo!)).to be true
    end

    it 'is true for bang methods when the key is a Hash' do
      subject[:foo] = Hashie::Hash[bar: 'abc']
      expect(subject.respond_to?(:foo!)).to be true
    end

    it 'is false for bang methods when the key is not chainable' do
      subject.foo('bar')
      expect(subject.respond_to?(:foo!)).to be false
    end

    it 'is true for any non-bang method' do
      expect(subject.respond_to?(:anything)).to be true
    end
  end

  describe 'when inherited' do
    subject { Class.new(described_class).new }

    it 'bang nodes are instances of a subclass' do
      subject.where!.foo(123)
      expect(subject[:where]).to be_instance_of(subject.class)
    end

    it 'merged nodes are instances of a subclass' do
      subject.where(abc: 'def').where(hgi: 123)
      expect(subject[:where]).to be_instance_of(subject.class)
    end
  end

  context 'when serialized' do
    let(:child) { described_class.new(name: 'child') }
    let(:source) do
      described_class.new(
        name: 'parent', child: child, entries: [nil, false, true, 42, 1.5, child]
      )
    end

    context 'through yaml' do
      let(:recovered) do
        yaml = Psych.dump(source)
        # Load only trusted YAML generated by this test.
        Psych.respond_to?(:unsafe_load) ? Psych.unsafe_load(yaml) : Psych.load(yaml)
      end

      it 'preserves classes and values at every level' do
        expect(recovered).to be_an_instance_of(described_class)
        expect(recovered).to eq source
        expect(recovered[:child]).to be_an_instance_of(described_class)
        expect(recovered[:child][:name]).to eq 'child'
        expect(recovered[:entries].last).to be_an_instance_of(described_class)
        expect(recovered[:entries].last[:name]).to eq 'child'
      end

      it 'creates independent objects and nested containers' do
        expect(recovered).not_to equal(source)
        expect(recovered[:child]).not_to equal(source[:child])
        expect(recovered[:entries]).not_to equal(source[:entries])
        recovered[:child][:name] = 'changed'
        recovered[:entries] << 'added'

        expect(source[:child][:name]).to eq 'child'
        expect(source[:entries].size).to eq 6
      end

      it 'preserves chained writes' do
        expect(recovered.child!.name('changed')).to equal(recovered[:child])
        expect(recovered[:child][:name]).to eq 'changed'
      end

      it 'preserves parent links created through bang chaining' do
        source.where!.name('nested')

        expect(recovered[:where]._end!).to equal(recovered)
        expect(recovered[:where][:name]).to eq 'nested'
      end

      it 'preserves named subclasses' do
        instance = SerializationFixtures::Clash.new(name: 'subclass')
        yaml = Psych.dump(instance)
        copy = Psych.respond_to?(:unsafe_load) ? Psych.unsafe_load(yaml) : Psych.load(yaml)

        expect(copy).to be_an_instance_of(SerializationFixtures::Clash)
        expect(copy).to eq instance
      end

      it 'keeps serialization metadata separate from stored keys' do
        source[:hash] = 'stored hash'
        source[:parent] = 'stored parent'

        expect(recovered[:hash]).to eq 'stored hash'
        expect(recovered[:parent]).to eq 'stored parent'
        expect(recovered._parent).to be_nil
      end
    end

    context 'through marshal' do
      let(:recovered) { Marshal.load(Marshal.dump(source)) }

      before do
        pending('MRI calls the advertised marshal_dump hook, which raises NoMethodError') if RUBY_ENGINE == 'ruby'
      end

      it 'preserves classes and values at every level' do
        expect(recovered).to be_an_instance_of(described_class)
        expect(recovered).to eq source
        expect(recovered[:child]).to be_an_instance_of(described_class)
        expect(recovered[:child][:name]).to eq 'child'
        expect(recovered[:entries].last).to be_an_instance_of(described_class)
        expect(recovered[:entries].last[:name]).to eq 'child'
      end

      it 'creates independent objects and nested containers' do
        expect(recovered).not_to equal(source)
        expect(recovered[:child]).not_to equal(source[:child])
        expect(recovered[:entries]).not_to equal(source[:entries])
        recovered[:child][:name] = 'changed'
        recovered[:entries] << 'added'

        expect(source[:child][:name]).to eq 'child'
        expect(source[:entries].size).to eq 6
      end

      it 'preserves chained writes' do
        expect(recovered.child!.name('changed')).to equal(recovered[:child])
        expect(recovered[:child][:name]).to eq 'changed'
      end
    end
  end
end
